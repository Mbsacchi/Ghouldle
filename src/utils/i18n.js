export function translateAttr(val, lang = 'pt') {
  if (lang !== 'en') {
    return Array.isArray(val) ? val.join(', ') : val;
  }
  if (Array.isArray(val)) {
    return val.map((item) => VALUE_TRANSLATIONS_EN[item] || item).join(', ');
  }
  return VALUE_TRANSLATIONS_EN[val] || val;
}

export function localizeCharacter(character, lang = 'pt') {
  if (!character || lang !== 'en') return character;
  const loc = CHARACTER_LOCALIZATION_EN[character.id];
  if (!loc) return character;

  return {
    ...character,
    epithet: loc.epithet || character.epithet,
    quote: {
      ...character.quote,
      text: loc.quote || character.quote?.text,
      arc: VALUE_TRANSLATIONS_EN[character.quote?.arc] || character.quote?.arc,
      recipient: loc.recipient || character.quote?.recipient,
    },
    maskOrEye: {
      ...character.maskOrEye,
      type: loc.maskType || character.maskOrEye?.type,
      title: loc.maskTitle || character.maskOrEye?.title,
    },
    kaguneOrQuinque: {
      ...character.kaguneOrQuinque,
      name: loc.weapon || character.kaguneOrQuinque?.name,
      category:
        VALUE_TRANSLATIONS_EN[character.kaguneOrQuinque?.category] ||
        character.kaguneOrQuinque?.category,
    },
  };
}
